function applyBranchReward(tree, branch) {
  if (branch.reward?.type !== "故事文本") return;
  const story = stories.find((item) => item.theme === tree.id);
  if (!story) return;
  branch.reward.text.forEach((line) => {
    if (!story.text.includes(line)) story.text.push(line);
  });
}

