function paginateChapterText(lines, format) {
  if (!lines.length) return [[]];
  const compactLandscape = window.matchMedia(
    "(orientation: landscape) and (max-height: 560px) and (max-width: 980px)"
  ).matches;
  const pageLimit = compactLandscape ? 700 : window.innerWidth <= 700 ? 900 : 1500;
  const pages = [];
  let page = [];
  let pageWeight = 0;

  lines.forEach((line) => {
    const dialogueWeight = format === "dialogue" && line.startsWith("「") ? 90 : 34;
    const lineWeight = line.length + dialogueWeight;
    if (page.length > 0 && pageWeight + lineWeight > pageLimit) {
      pages.push(page);
      page = [];
      pageWeight = 0;
    }
    page.push(line);
    pageWeight += lineWeight;
  });

  if (page.length > 0) pages.push(page);
  return pages;
}

function showChapterPage(pageIndex, scrollToTop = true) {
  if (!activeChapterPages.length) return;
  activeChapterPage = Math.max(0, Math.min(pageIndex, activeChapterPages.length - 1));
  if (activeChapterKey) chapterPageMemory.set(activeChapterKey, activeChapterPage);
  const lines = activeChapterPages[activeChapterPage];
  chapterText.replaceChildren();

  if (activeChapterFormat === "dialogue") {
    chapterText.classList.add("chapter-text--dialogue");
    chapterText.classList.toggle("chapter-text--storyboard", activeChapterStoryboard);
    chapterText.classList.toggle("has-inner-monologue", lines.some((line) => activeChapterInnerMonologue.has(line)));
    let monologueLabelAdded = false;
    lines.forEach((line, index) => {
      const block = document.createElement(line.startsWith("「") ? "blockquote" : "p");
      block.className = line.startsWith("「") ? "chapter-dialogue" : "chapter-narration";
      if (activeChapterStoryboard && line.startsWith("【") && line.endsWith("】")) {
        block.classList.add("chapter-storyboard-label");
      }
      if (activeChapterStoryboard && line.includes("【蒙太奇】")) {
        block.classList.add("chapter-storyboard-montage");
      }
      if (activeChapterInnerMonologue.has(line)) {
        block.classList.add("chapter-inner-monologue");
        if (!monologueLabelAdded) {
          block.classList.add("chapter-inner-monologue-start");
          monologueLabelAdded = true;
        }
      }
      block.style.setProperty("--delay", `${Math.min(index * 35, 350)}ms`);
      block.textContent = line;
      chapterText.appendChild(block);
    });
  } else {
    chapterText.classList.remove("chapter-text--dialogue");
    chapterText.classList.remove("chapter-text--storyboard");
    chapterText.classList.remove("has-inner-monologue");
    if (lines.length > 0) {
      const paragraph = document.createElement("p");
      paragraph.textContent = lines.join(" ");
      chapterText.appendChild(paragraph);
    }
  }

  if (activeChapterChallenge === "myth-final-password" && activeChapterPage === activeChapterPages.length - 1) {
    renderFinalPasswordChallenge();
  }
  if (activeChapterChallenge === "fall-expectation" && activeChapterPage === activeChapterPages.length - 1) {
    renderFallExpectationChallenge();
  }

  const hasMultiplePages = activeChapterPages.length > 1;
  chapterPagination.hidden = !hasMultiplePages;
  chapterPagePrev.disabled = activeChapterPage === 0;
  chapterPageNext.disabled = activeChapterPage === activeChapterPages.length - 1;
  chapterPageStatus.textContent = `第 ${activeChapterPage + 1} / ${activeChapterPages.length} 頁`;

  if (scrollToTop) {
    chapterModal.querySelector(".chapter-sheet").scrollTo({ top: 0, behavior: "smooth" });
  }
}

function navigateChapterPage(direction) {
  const nextPage = activeChapterPage + direction;
  if (nextPage < 0 || nextPage >= activeChapterPages.length) return;
  chapterText.classList.remove("is-swipe-left", "is-swipe-right");
  void chapterText.offsetWidth;
  chapterText.classList.add(direction > 0 ? "is-swipe-left" : "is-swipe-right");
  showChapterPage(nextPage);
}

function enableChapterSwipe() {
  let startX = 0;
  let startY = 0;
  let tracking = false;

  chapterModal.addEventListener("touchstart", (event) => {
    const target = event.target;
    if (target.closest("button, input, textarea, select, a")) return;
    const touch = event.touches[0];
    if (!touch) return;
    startX = touch.clientX;
    startY = touch.clientY;
    tracking = true;
  }, { passive: true });

  chapterModal.addEventListener("touchend", (event) => {
    if (!tracking) return;
    tracking = false;
    const touch = event.changedTouches[0];
    if (!touch) return;
    const deltaX = touch.clientX - startX;
    const deltaY = touch.clientY - startY;
    if (Math.abs(deltaX) < 58 || Math.abs(deltaX) <= Math.abs(deltaY) * 1.25) return;
    navigateChapterPage(deltaX < 0 ? 1 : -1);
  }, { passive: true });
}

